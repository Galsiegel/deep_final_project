def confusion_matrix_3(y_true, y_pred):
    cm = np.zeros((3,3), dtype=int)
    for t, p in zip(y_true, y_pred):
        cm[int(t), int(p)] += 1
    return cm


def macro_f1_from_cm(cm):
    f1s = []
    for k in range(3):
        tp = cm[k, k]
        fp = cm[:, k].sum() - tp
        fn = cm[k, :].sum() - tp

        prec = tp / (tp + fp + 1e-9)
        rec  = tp / (tp + fn + 1e-9)   # <-- no /100

        f1 = 2 * prec * rec / (prec + rec + 1e-9)
        f1s.append(f1)
    return float(np.mean(f1s))



