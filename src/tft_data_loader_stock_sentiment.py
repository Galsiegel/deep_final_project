class MasterStockDataset(Dataset):
    def __init__(self, master_file_path: Path):
        data_list = torch.load(master_file_path, weights_only=False)
        self.X = torch.tensor(np.array([s['x'] for s in data_list]), dtype=torch.float32)          # (N,T,F)
        self.y = torch.tensor(np.array([s['y'] for s in data_list]), dtype=torch.long)             # (N,)
        self.sid = torch.tensor(np.array([s['static_id'] for s in data_list]), dtype=torch.long)   # (N,)
