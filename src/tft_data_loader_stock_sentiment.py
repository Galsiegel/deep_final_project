def get_window_label_rigorous(df: pd.DataFrame, t: int, multiplier: float, target_days: int):
    """
    Triple Barrier:
      label: 0=Sell, 1=Neutral, 2=Buy
      barriers: around next day's open, width = multiplier * ATR(t)
      lookahead: 1..target_days
      if both hit same day => Neutral
    """
    atr_t = df.iloc[t]['ATR_Abs']
    open_next = df.iloc[t+1]['Open']

    buy_lvl  = open_next + (atr_t * multiplier)
    sell_lvl = open_next - (atr_t * multiplier)

    label = 1
    is_v = False
    trigger_idx = None
    trigger_type = None

    for k in range(1, target_days + 1):
        idx = t + k
        if idx >= len(df): break

        h, l = df.iloc[idx]['High'], df.iloc[idx]['Low']
        hit_buy  = h >= buy_lvl
        hit_sell = l <= sell_lvl

        if hit_buy and hit_sell:
            is_v = True
            trigger_idx = idx
            trigger_type = 'both'
            label = 1
            break
        elif hit_buy:
            trigger_idx = idx
            trigger_type = 'buy'
            label = 2
            break
        elif hit_sell:
            trigger_idx = idx
            trigger_type = 'sell'
            label = 0
            break

    return label, is_v, trigger_idx, trigger_type

