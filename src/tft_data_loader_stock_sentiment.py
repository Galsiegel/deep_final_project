@torch.no_grad()
def eval_loader(model, loader, criterion):
    model.eval()
    total_loss = 0.0
    total_correct = 0
    all_preds, all_true = [], []

    for x, sid, y, idx in loader:
        x, sid, y = x.to(DEVICE), sid.to(DEVICE), y.to(DEVICE)

        logits = model(x, sid)
        loss = criterion(logits, y)

        total_loss += loss.item()
        preds = logits.argmax(1)
        total_correct += (preds == y).sum().item()

        all_preds.extend(preds.cpu().numpy())
        all_true.extend(y.cpu().numpy())

    avg_loss = total_loss / max(len(loader), 1)
    acc = total_correct / max(len(loader.dataset), 1)

    cm = confusion_matrix_3(all_true, all_preds)
    mf1 = macro_f1_from_cm(cm)
    return avg_loss, acc, mf1, cm, all_true, all_preds

