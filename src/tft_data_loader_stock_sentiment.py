class DifferentiableTFTLoss(nn.Module):
    def __init__(self, alpha=None, gamma=2.0, directional_weight=1.0):
        super(DifferentiableTFTLoss, self).__init__()
        self.gamma = gamma
        self.directional_weight = directional_weight
        # Standard CE (reduction='none' so we can weight it by focal term)
        self.ce = nn.CrossEntropyLoss(weight=alpha, reduction='none')

    def forward(self, logits, targets):
        # 1. Focal Loss Part
        ce_loss = self.ce(logits, targets)
        pt = torch.exp(-ce_loss)
        focal_loss = ((1 - pt) ** self.gamma * ce_loss).mean()

        # 2. Differentiable Directional Penalty
        # We want to minimize the Probability of Sell (idx 0) if Target is Buy (2)
        # We want to minimize the Probability of Buy (idx 2) if Target is Sell (0)

        probs = F.softmax(logits, dim=1) # Shape: [Batch, 3]

        # Create masks (Float for multiplication)
        target_is_sell = (targets == 0).float()
        target_is_buy  = (targets == 2).float()

        # Probabilities assigned to the "Wrong Extreme"
        # If True=Sell, penalty is the Prob assigned to Buy
        # If True=Buy, penalty is the Prob assigned to Sell
        prob_buy  = probs[:, 2]
        prob_sell = probs[:, 0]

        dir_penalty_term = (target_is_sell * prob_buy) + (target_is_buy * prob_sell)

        # Mean over the batch
        directional_penalty = dir_penalty_term.mean() * self.directional_weight

        return focal_loss + directional_penalty

# ==========================================
# 1. Custom SOTA Loss: Focal + Directional
# ==========================================
class TFTLoss(nn.Module):
    def __init__(self, alpha=None, gamma=1.5, directional_weight=0.5):
        super(TFTLoss, self).__init__()
        self.gamma = gamma
        self.directional_weight = directional_weight
        self.ce = nn.CrossEntropyLoss(weight=alpha, reduction='none')

    def forward(self, logits, targets):
        ce_loss = self.ce(logits, targets)
        pt = torch.exp(-ce_loss)

        # Focal Loss to handle hard samples
        focal_loss = ((1 - pt) ** self.gamma * ce_loss).mean()

        probs = F.softmax(logits, dim=1)
        pred_labels = torch.argmax(probs, dim=1)

        # Directional Penalty (dw): Significant penalty for full reversals
        opposite_mask = ((targets == 2) & (pred_labels == 0)) | ((targets == 0) & (pred_labels == 2))
        directional_penalty = opposite_mask.float().mean() * self.directional_weight

        return focal_loss + directional_penalty


