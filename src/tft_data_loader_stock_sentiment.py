class StockTFT(nn.Module):
    def __init__(
        self,
        input_dim=12,
        hidden_dim=128,
        n_heads=8,
        output_dim=3,
        dropout=0.2,
        num_stocks=None,
        stock_emb_dim=16,
    ):
        super().__init__()

        # ---- feature encoder ----
        self.vsn = VSN(input_dim, hidden_dim, dropout)

        # ---- optional stock embedding ----
        self.use_stock_emb = (num_stocks is not None) and (stock_emb_dim > 0)
        if self.use_stock_emb:
            self.stock_emb = nn.Embedding(num_stocks, stock_emb_dim)
            pre_dim = hidden_dim + stock_emb_dim
        else:
            self.stock_emb = None
            pre_dim = hidden_dim

        # ---- pre-LSTM ----
        self.pre_lstm_ln = nn.LayerNorm(pre_dim)
        self.pre_lstm_proj = nn.Linear(pre_dim, hidden_dim)

        # ---- temporal encoder ----
        self.lstm = nn.LSTM(
            hidden_dim, hidden_dim,
            num_layers=1,
            batch_first=True,
            bidirectional=True
        )

        self.mha = nn.MultiheadAttention(
            embed_dim=hidden_dim * 2,
            num_heads=n_heads,
            dropout=dropout,
            batch_first=True
        )

        self.post_attn_grn = GRN(hidden_dim * 2, hidden_dim, hidden_dim * 2, dropout=dropout)
        self.classifier = nn.Linear(hidden_dim * 2, output_dim)

    def forward(self, x, sid=None):
        # x: (B,T,F=input_dim)
        x = self.vsn(x)  # (B,T,H)

        if self.use_stock_emb:
            if sid is None:
                raise ValueError("sid must be provided when num_stocks/stock_emb_dim are set.")
            e = self.stock_emb(sid)                      # (B,E)
            e = e.unsqueeze(1).expand(-1, x.size(1), -1) # (B,T,E)
            x = torch.cat([x, e], dim=-1)                # (B,T,H+E)

        x = self.pre_lstm_ln(x)
        x = self.pre_lstm_proj(x)  # (B,T,H)

        lstm_out, _ = self.lstm(x)                # (B,T,2H)
        attn_out, _ = self.mha(lstm_out, lstm_out, lstm_out)
        x = self.post_attn_grn(attn_out)

        return self.classifier(x[:, -1, :])

