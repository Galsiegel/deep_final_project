class VSN(nn.Module):
    def __init__(self, input_dim, hidden_dim, dropout=0.1):
        super().__init__()
        self.input_dim = input_dim
        self.hidden_dim = hidden_dim

        self.feature_grns = nn.ModuleList([
            GRN(1, hidden_dim, hidden_dim, dropout) for _ in range(input_dim)
        ])

        # simpler selector: concat -> hidden -> logits (no LN on giant vector)
        self.selector = nn.Sequential(
            nn.Linear(input_dim * hidden_dim, hidden_dim),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, input_dim)
        )

        self.softmax = nn.Softmax(dim=-1)

    def forward(self, x):
        B, T, D = x.shape

        feats = []
        for i in range(D):
            feats.append(self.feature_grns[i](x[:, :, i:i+1]))  # [B,T,H]

        combined = torch.cat(feats, dim=-1)        # [B,T,D*H]
        logits = self.selector(combined)           # [B,T,D]
        weights = self.softmax(logits).unsqueeze(-1)  # [B,T,D,1]

        stacked = torch.stack(feats, dim=2)        # [B,T,D,H]
        out = (weights * stacked).sum(dim=2)       # [B,T,H]
        assert D == len(self.feature_grns), f"VSN mismatch: input D={D}, feature_grns={len(self.feature_grns)}"

        self.last_weights = weights.detach()

        return out


