def get_label_fast(np_high, np_low, np_open, np_atr, t, multiplier, target_days):
    # Match A: day-by-day scan; Buy check first; no "both-hit => Neutral"
    if t + 1 >= len(np_open):
        return 1, False, None, None

    atr_t = np_atr[t]
    open_next = np_open[t + 1]

    buy_lvl  = open_next + (atr_t * multiplier)
    sell_lvl = open_next - (atr_t * multiplier)

    sl_start = t + 1
    sl_end = min(t + target_days + 1, len(np_open))

    w_high = np_high[sl_start:sl_end]
    w_low  = np_low[sl_start:sl_end]

    for i in range(len(w_high)):  # i=0 corresponds to day t+1
        hit_buy  = w_high[i] >= buy_lvl
        hit_sell = w_low[i]  <= sell_lvl

        if hit_buy:
            # A logic: Buy wins even if both hit same day
            is_v = bool(hit_sell)  # True only if both hit on trigger day
            trig_type = 'both' if is_v else 'buy'
            return 2, is_v, sl_start + i, trig_type

        if hit_sell:
            # Sell trigger day (cannot be both, because buy would have returned above)
            return 0, False, sl_start + i, 'sell'

    return 1, False, None, None



