def macro_f1_from_cm(cm, verbose=True):
    """
    Computes Macro F1 from a confusion matrix and optionally prints a detailed report.

    Args:
        cm (np.array): Confusion matrix of shape (C, C).
                       Rows = True, Cols = Predicted.
        verbose (bool): If True, prints precision/recall/f1 for each class.

    Returns:
        float: The Macro F1 score (mean of per-class F1s).
    """
    num_classes = cm.shape[0]
    f1s = []

    if verbose:
        print(f"{'Class':<6} | {'Prec.':<10} | {'Recall':<10} | {'F1':<10} | {'Count':<8}")
        print("-" * 55)
    else:
        pass # Added pass for no-op when verbose is False

    epsilon = 1e-9  # Prevention for division by zero

    for k in range(num_classes):
        # True Positives: Diagonal element
        tp = cm[k, k]

        # False Positives: Sum of column k minus TP
        fp = cm[:, k].sum() - tp

        # False Negatives: Sum of row k minus TP
        fn = cm[k, :].sum() - tp

        # Support: Total actual instances of this class
        support = cm[k, :].sum()

        # Metrics calculation
        prec = tp / (tp + fp + epsilon)
        rec  = tp / (tp + fn + epsilon)
        f1   = 2 * (prec * rec) / (prec + rec + epsilon)

        f1s.append(f1)

        if verbose:
            # print(f"{k:<6} | {prec:.4f}     | {rec:.4f}     | {f1:.4f}     | {support:<8}")
            pass # Added pass to fix IndentationError

    macro_f1 = float(np.mean(f1s))

    if verbose:
        # print("-" * 55)
        # print(f"Macro F1: {macro_f1:.4f}")
        # print("\n")
        pass # Added pass to fix IndentationError

    return macro_f1

