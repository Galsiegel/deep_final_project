@torch.no_grad()
def collect_importance_df(model, loader, base_dataset, feature_names=None, mode="mean_time"):
    """
    mode:
      - "mean_time": average VSN weights over time -> [B, D]
      - "last": use last timestep weights -> [B, D]
    """
    model.eval()

    # infer D
    # VSN weights are [B,T,D,1] => squeeze -> [B,T,D]
    rows = []
    D = None

    for x, sid, y, idx in loader:
        x = x.to(DEVICE)
        sid = sid.to(DEVICE)
        y = y.to(DEVICE)

        logits = model(x, sid)
        preds = logits.argmax(dim=1)

        w = model.vsn.last_weights  # [B,T,D,1]
        w = w.squeeze(-1)           # [B,T,D]
        if D is None:
            D = w.shape[-1]

        if mode == "mean_time":
            imp = w.mean(dim=1)     # [B,D]
        elif mode == "last":
            imp = w[:, -1, :]       # [B,D]
        else:
            raise ValueError("mode must be 'mean_time' or 'last'")

        imp = imp.detach().cpu().numpy()
        sid_np = sid.detach().cpu().numpy()
        y_np = y.detach().cpu().numpy()
        p_np = preds.detach().cpu().numpy()
        idx_np = idx.detach().cpu().numpy() if torch.is_tensor(idx) else np.array(idx)

        for i in range(len(idx_np)):
            meta = base_dataset.metadata_list[int(idx_np[i])]
            ticker = meta.get("ticker", None)
            date_ns = meta.get("date_ns", None)

            row = {
                "idx": int(idx_np[i]),
                "sid": int(sid_np[i]),
                "ticker": ticker,
                "date_ns": int(date_ns) if date_ns is not None else None,
                "true": int(y_np[i]),
                "pred": int(p_np[i]),
            }

            # add feature importances as columns
            for j in range(D):
                col = feature_names[j] if feature_names is not None else f"f{j}"
                row[col] = float(imp[i, j])

            rows.append(row)

    df = pd.DataFrame(rows)
    if "date_ns" in df.columns and df["date_ns"].notna().any():
        df["date"] = pd.to_datetime(df["date_ns"], unit="ns").dt.date
    return df

